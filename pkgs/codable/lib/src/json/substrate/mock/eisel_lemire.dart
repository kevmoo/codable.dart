// Unsigned 64-bit comparisons.
//
// On the VM and Wasm `int` is a signed 64-bit integer, so a mantissa that has
// wrapped past 2^63 compares as negative; flipping the sign bit restores
// unsigned ordering. On the web `int` is a double and bitwise operators are
// evaluated with 32-bit semantics: `x ^ _bit63` truncates its operands to 32
// bits and yields `ToUint32(x)`, so the sign trick silently compares the low
// 32 bits of each side. Web values reaching these helpers are non-negative
// doubles, so a plain comparison is both correct and exact there.

@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
bool unsignedLe(int a, int b) =>
    identical(1, 1.0) ? a <= b : (a ^ _bit63) <= (b ^ _bit63);

@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
bool _unsignedLt(int a, int b) =>
    identical(1, 1.0) ? a < b : (a ^ _bit63) < (b ^ _bit63);

@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
int _clz64(int w) {
  if (w < 0) {
    return 0;
  }
  if (w == 0) {
    return 64;
  }
  return 64 - w.bitLength;
}

@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
int _mul64x64High(int a, int b) {
  final aLo = a & 0xFFFFFFFF;
  final aHi = a >>> 32;
  final bLo = b & 0xFFFFFFFF;
  final bHi = b >>> 32;

  final p0 = aLo * bLo;
  final p1 = aLo * bHi;
  final p2 = aHi * bLo;
  final p3 = aHi * bHi;

  final cy0 = (p0 >>> 32) + (p1 & 0xFFFFFFFF) + (p2 & 0xFFFFFFFF);
  return p3 + (p1 >>> 32) + (p2 >>> 32) + (cy0 >>> 32);
}

final ByteData _sharedFloat64Buffer = ByteData(8);

@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
double _doubleFromBits(int bits) {
  _sharedFloat64Buffer.setInt64(0, bits, Endian.host);
  return _sharedFloat64Buffer.getFloat64(0, Endian.host);
}

@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
bool _isAmbiguousHalfway(int hi, int shiftedLo) {
  final low11 = hi & 0x7FF;
  if (low11 == 0x3FF) {
    final loPlusErr = shiftedLo + 1;
    return _unsignedLt(loPlusErr, shiftedLo);
  }
  return low11 == 0x400 && shiftedLo == 0;
}

@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
double? _roundAndPackEiselLemire(
  int hi,
  int lo,
  int qIndex,
  int lz,
  bool isNegative,
) {
  final isBit63Set = (hi & _bit63) != 0;
  final finalShift = isBit63Set ? 0 : 1;
  final normHi = isBit63Set ? hi : ((hi << 1) | (lo >>> 63));
  final shiftedLo = isBit63Set ? lo : (lo << 1);

  final biasedExp = _power10Exp[qIndex] - lz - finalShift + 1023 + 63;
  if (biasedExp <= 0 ||
      biasedExp >= 2047 ||
      _isAmbiguousHalfway(normHi, shiftedLo)) {
    return null;
  }

  var mantissaBits = normHi + 0x400;
  var finalExp = biasedExp;
  if (_unsignedLt(mantissaBits, normHi)) {
    mantissaBits = (mantissaBits >>> 1) | _bit63;
    finalExp++;
    if (finalExp >= 2047) {
      return null;
    }
  }

  final fractionBits = (mantissaBits >>> 11) & 0x000FFFFFFFFFFFFF;
  final signBit = isNegative ? _bit63 : 0;
  final floatBits = signBit | (finalExp << 52) | fractionBits;

  return _doubleFromBits(floatBits);
}

/// Pure-Dart 64-bit IEEE-754 Eisel-Lemire floating-point converter.
///
/// Returns `null` when [decimalExp] is out of table bounds, on JS runtimes
/// (`identical(1, 1.0)`), on subnormal/overflow exponents, or when the 192-bit
/// product falls within the midpoint ambiguity window requiring fallback.
@pragma('vm:prefer-inline')
@pragma('wasm:prefer-inline')
double? tryParseDoubleFastEiselLemire(
  int mantissa,
  int decimalExp,
  bool isNegative,
) {
  if (mantissa == 0) {
    return isNegative ? -0.0 : 0.0;
  }

  if (decimalExp == 0 && unsignedLe(mantissa, 0x001FFFFFFFFFFFFF)) {
    return isNegative ? -mantissa.toDouble() : mantissa.toDouble();
  }

  if (decimalExp < -342 || decimalExp > 308 || identical(1, 1.0)) {
    return null;
  }

  final power10H = _power10H;
  final power10L = _power10L;
  if (power10H == null || power10L == null) {
    return null;
  }

  final qIndex = decimalExp + 342;
  final lz = _clz64(mantissa);
  final normMantissa = mantissa << lz;

  // 192-bit full multiplication: normMantissa * (H_q * 2^64 + L_q)
  final p1Hi = _mul64x64High(normMantissa, power10L[qIndex]);

  final aLo = normMantissa & 0xFFFFFFFF;
  final aHi = normMantissa >>> 32;
  final bLo = power10H[qIndex] & 0xFFFFFFFF;
  final bHi = power10H[qIndex] >>> 32;

  final p0 = aLo * bLo;
  final p1 = aLo * bHi;
  final p2 = aHi * bLo;
  final p3 = aHi * bHi;

  final cy0 = (p0 >>> 32) + (p1 & 0xFFFFFFFF) + (p2 & 0xFFFFFFFF);
  final p2Lo = (p0 & 0xFFFFFFFF) | ((cy0 & 0xFFFFFFFF) << 32);
  var p2Hi = p3 + (p1 >>> 32) + (p2 >>> 32) + (cy0 >>> 32);

  final lo = p2Lo + p1Hi;
  if (_unsignedLt(lo, p1Hi)) {
    p2Hi++;
  }

  return _roundAndPackEiselLemire(p2Hi, lo, qIndex, lz, isNegative);
}
